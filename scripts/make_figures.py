#!/usr/bin/env python3
"""Turn the committed metrics snapshot into pgfplots figure sources.

Figures are emitted as LaTeX rather than raster images so the paper has no
binary dependencies and the numbers on every axis trace back to
``data/metrics.json``.

Usage::

    python3 scripts/make_figures.py
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "metrics.json"
FIGDIR = ROOT / "figures"

# Short labels for the plots; the full slug is unreadable on a narrow axis.
LABELS = {
    "d3/d3": "D3",
    "vega/vega": "Vega",
    "vega/vega-lite": "Vega-Lite",
    "vega/altair": "Altair",
    "uwdata/mosaic": "Mosaic",
    "observablehq/plot": "Plot",
    "apache/echarts": "ECharts",
    "plotly/plotly.js": "plotly.js",
    "plotly/plotly.py": "plotly.py",
    "chartjs/Chart.js": "Chart.js",
    "visgl/deck.gl": "deck.gl",
    "matplotlib/matplotlib": "Matplotlib",
    "bokeh/bokeh": "Bokeh",
    "holoviz/holoviews": "HoloViews",
    "mwaskom/seaborn": "seaborn",
}


def load() -> tuple[list[dict], datetime]:
    if not DATA.exists():
        sys.exit(f"missing {DATA}; run scripts/collect_metrics.py first")
    blob = json.loads(DATA.read_text())
    stamp = datetime.fromisoformat(blob["collected_at"])
    return blob["repositories"], stamp


def label(row: dict) -> str:
    return LABELS.get(row["slug"], row["slug"].split("/")[-1])


def years_active(row: dict, now: datetime) -> float:
    created = datetime.fromisoformat(row["created_at"].replace("Z", "+00:00"))
    return (now - created).days / 365.25


def fig_reach(rows: list[dict], now: datetime) -> str:
    """Stars against contributors, split by whether the project is research-born.

    The point of the figure is that the two populations do not separate: papers
    are not a handicap in adoption, nor a guarantee of it.
    """
    def series(research: bool) -> str:
        pts = []
        for r in rows:
            if r["research_origin"] != research or not r["contributors"]:
                continue
            pts.append(
                f"    ({r['contributors']},{r['stars']}) "
                f"[{label(r)}]"
            )
        return "\n".join(pts)

    return rf"""% Generated by scripts/make_figures.py -- do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\columnwidth, height=0.72\columnwidth,
  xmode=log, ymode=log,
  xlabel={{Contributors}}, ylabel={{Stars}},
  label style={{font=\scriptsize}}, tick label style={{font=\scriptsize}},
  legend style={{font=\scriptsize, at={{(0.02,0.98)}}, anchor=north west,
                draw=none, fill=none}},
  grid=both, grid style={{gray!18}},
  log ticks with fixed point,
  enlarge x limits=0.18, enlarge y limits=0.18,
]
\addplot[only marks, mark=*, mark size=1.9pt, color=vislink,
         point meta=explicit symbolic,
         nodes near coords, nodes near coords align={{above right}},
         every node near coord/.append style={{font=\tiny, color=black!70}}]
  coordinates {{
{series(True)}
  }};
\addlegendentry{{research-origin}}
\addplot[only marks, mark=o, mark size=1.9pt, color=black!55,
         point meta=explicit symbolic,
         nodes near coords, nodes near coords align={{above right}},
         every node near coord/.append style={{font=\tiny, color=black!70}}]
  coordinates {{
{series(False)}
  }};
\addlegendentry{{practitioner-origin}}
\end{{axis}}
\end{{tikzpicture}}
"""


def fig_longevity(rows: list[dict], now: datetime) -> str:
    """Age of each project, sorted, annotated with research origin."""
    ordered = sorted(rows, key=lambda r: years_active(r, now))
    bars, ticks = [], []
    for i, r in enumerate(ordered):
        bars.append(f"    ({years_active(r, now):.2f},{i})")
        ticks.append(f"{i}/{label(r)}")
    research_bars = [
        f"    ({years_active(r, now):.2f},{i})"
        for i, r in enumerate(ordered) if r["research_origin"]
    ]
    return rf"""% Generated by scripts/make_figures.py -- do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\columnwidth, height=0.95\columnwidth,
  xbar, xmin=0,
  xlabel={{Years since first commit}},
  ytick={{{",".join(str(i) for i in range(len(ordered)))}}},
  yticklabels={{{",".join(label(r) for r in ordered)}}},
  label style={{font=\scriptsize}}, tick label style={{font=\scriptsize}},
  bar width=4pt, y=11pt,
  grid=major, grid style={{gray!18}},
  enlarge y limits={{abs=8pt}},
]
\addplot[xbar, fill=black!25, draw=none] coordinates {{
{chr(10).join(bars)}
}};
\addplot[xbar, fill=vislink, draw=none] coordinates {{
{chr(10).join(research_bars)}
}};
\end{{axis}}
\end{{tikzpicture}}
"""


def thousands(n: int) -> str:
    """LaTeX-safe thousands separator (a bare comma in math mode is spacing)."""
    return f"{n:,}".replace(",", "{,}")


def numbers(rows: list[dict], now: datetime) -> str:
    """Emit every figure quoted in the prose as a macro.

    Keeping the numbers in one generated file means the paper cannot drift
    from the snapshot: if a value changes, it changes everywhere at once.
    """
    research = [r for r in rows if r["research_origin"]]
    practice = [r for r in rows if not r["research_origin"]]
    with_contrib = [r for r in rows if r["contributors"]]

    def median(vals: list[float]) -> float:
        s = sorted(vals)
        n = len(s)
        return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2

    lines = [
        "% Generated by scripts/make_figures.py -- do not edit.",
        rf"\newcommand{{\snapshotdate}}{{{now:%-d %B %Y}}}",
        rf"\newcommand{{\ncorpus}}{{{len(rows)}}}",
        rf"\newcommand{{\nresearch}}{{{len(research)}}}",
        rf"\newcommand{{\npractice}}{{{len(practice)}}}",
        rf"\newcommand{{\medianage}}{{{median([years_active(r, now) for r in rows]):.1f}}}",
        rf"\newcommand{{\medianstarsresearch}}{{{thousands(int(median([r['stars'] for r in research])))}}}",
        rf"\newcommand{{\medianstarspractice}}{{{thousands(int(median([r['stars'] for r in practice])))}}}",
        rf"\newcommand{{\totalstars}}{{{thousands(sum(r['stars'] for r in rows))}}}",
        rf"\newcommand{{\totalcontrib}}{{{thousands(sum(r['contributors'] for r in with_contrib))}}}",
    ]
    for r in rows:
        key = "".join(c for c in label(r) if c.isalpha()).lower()
        lines.append(rf"\newcommand{{\{key}stars}}{{{thousands(r['stars'])}}}")
        if r["contributors"]:
            lines.append(
                rf"\newcommand{{\{key}contrib}}{{{thousands(r['contributors'])}}}"
            )
        lines.append(
            rf"\newcommand{{\{key}age}}{{{years_active(r, now):.0f}}}"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    rows, stamp = load()
    now = stamp
    FIGDIR.mkdir(parents=True, exist_ok=True)

    (ROOT / "paper" / "numbers.tex").write_text(numbers(rows, now))
    print("wrote paper/numbers.tex", file=sys.stderr)

    outputs = {
        "reach.tex": fig_reach(rows, now),
        "longevity.tex": fig_longevity(rows, now),
    }
    for name, body in outputs.items():
        (FIGDIR / name).write_text(body)
        print(f"wrote figures/{name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
