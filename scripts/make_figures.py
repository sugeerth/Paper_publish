#!/usr/bin/env python3
"""Turn the mined history into pgfplots figures and LaTeX macros.

Figures are emitted as LaTeX source rather than raster images so that every
value on every axis traces back to ``data/*.json`` and the paper carries no
binary assets.

Usage::

    python3 scripts/make_figures.py
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
FIGDIR = ROOT / "figures"
PAPER = ROOT / "paper"

# Repositories drawn on the lineage timeline, in publication order, with the
# venue that introduced them. Ordering is chronological by first commit.
TIMELINE = [
    ("protovis",     "Protovis",     "InfoVis'09"),
    ("d3",           "D3",           "InfoVis'11"),
    ("vega",         "Vega",         "InfoVis'16"),
    ("lyra",         "Lyra",         "EuroVis'14"),
    ("vega-lite",    "Vega-Lite",    "InfoVis'17"),
    ("voyager",      "Voyager",      "InfoVis'15"),
    ("draco",        "Draco",        "InfoVis'18"),
    ("falcon",       "Falcon",       "CHI'19"),
    ("altair",       "Altair",       "JOSS'18"),
    ("mosaic",       "Mosaic",       "VIS'24"),
]

# Comparison rows for the maintenance table.
TABLE_ROWS = [
    "vega-lite", "vega", "d3", "altair", "mosaic",
    "matplotlib", "bokeh", "echarts", "ggplot2", "plot",
]


def load(name: str) -> dict:
    path = DATA / name
    if not path.exists():
        sys.exit(f"missing {path}; run scripts/analyze_history.py first")
    return json.loads(path.read_text())


def tex_int(n: int) -> str:
    """Thousands separator that survives LaTeX (a bare comma is math spacing)."""
    return f"{n:,}".replace(",", "{,}")


# --------------------------------------------------------------------------
# Figure 1 -- who writes Vega-Lite's commits, per year
# --------------------------------------------------------------------------
def fig_bots(repos: dict) -> str:
    vl = next(r for r in repos["repositories"] if r["name"] == "vega-lite")
    years = sorted(set(vl["per_year_human"]) | set(vl["per_year_bot"]))
    human = [vl["per_year_human"].get(y, 0) for y in years]
    bot = [vl["per_year_bot"].get(y, 0) for y in years]

    def coords(vals: list[int]) -> str:
        return " ".join(f"({y},{v})" for y, v in zip(years, vals))

    return rf"""% Generated by scripts/make_figures.py -- do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\columnwidth, height=0.60\columnwidth,
  ybar stacked, bar width=6pt,
  xmin={int(years[0]) - 1}, xmax={int(years[-1]) + 1},
  xtick={{{",".join(years[::2])}}},
  x tick label style={{font=\scriptsize, rotate=45, anchor=east,
                       /pgf/number format/1000 sep={{}}}},
  ylabel={{Commits}}, ymin=0,
  label style={{font=\scriptsize}}, tick label style={{font=\scriptsize}},
  legend style={{font=\scriptsize, at={{(0.98,0.98)}}, anchor=north east,
                 draw=none, fill=white, fill opacity=0.85, text opacity=1}},
  grid=major, grid style={{gray!18}},
  axis lines*=left,
]
\addplot[fill=vislink, draw=none] coordinates {{{coords(human)}}};
\addlegendentry{{human}}
\addplot[fill=black!22, draw=none] coordinates {{{coords(bot)}}};
\addlegendentry{{bot}}
\end{{axis}}
\end{{tikzpicture}}
"""


# --------------------------------------------------------------------------
# Figure 2 -- active lifetime of each published system in the lineage
# --------------------------------------------------------------------------
def fig_timeline(repos: dict) -> str:
    by_name = {r["name"]: r for r in repos["repositories"]}
    rows = [(n, lab, ven) for n, lab, ven in TIMELINE if n in by_name]
    rows.sort(key=lambda t: by_name[t[0]]["first_commit"])

    def frac_year(iso: str) -> float:
        d = date.fromisoformat(iso)
        return d.year + (d.timetuple().tm_yday - 1) / 365.25

    bars, dead, live, labels = [], [], [], []
    for i, (name, label, venue) in enumerate(rows):
        r = by_name[name]
        start, end = frac_year(r["first_commit"]), frac_year(r["last_human_commit"])
        bars.append(rf"\draw[line width=3.2pt, black!20] "
                    rf"(axis cs:{start:.2f},{i}) -- (axis cs:{end:.2f},{i});")
        # A project is "dormant" if no human has committed in the last 12 months.
        target = dead if r["human_commits_12mo"] == 0 else live
        target.append(f"({end:.2f},{i})")
        labels.append(f"{i}/{{{label}\\,\\tiny {venue}}}")

    snapshot = frac_year(repos["snapshot"])
    return rf"""% Generated by scripts/make_figures.py -- do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\columnwidth, height=0.78\columnwidth,
  xmin=2008.5, xmax={snapshot + 0.5:.2f},
  ymin=-0.8, ymax={len(rows) - 0.2:.1f},
  ytick={{{",".join(str(i) for i in range(len(rows)))}}},
  yticklabels={{{",".join(lab.split("/", 1)[1] for lab in labels)}}},
  xtick={{2010,2014,2018,2022,2026}},
  label style={{font=\scriptsize}}, tick label style={{font=\scriptsize}},
  x tick label style={{font=\scriptsize, /pgf/number format/1000 sep={{}}}},
  y tick label style={{font=\scriptsize}},
  xlabel={{}},
  grid=none,
  axis lines*=left, y axis line style={{draw=none}}, ytick style={{draw=none}},
  clip=false,
  legend style={{font=\scriptsize, at={{(0.5,-0.14)}}, anchor=north,
                 legend columns=2, draw=none, fill=none}},
]
{chr(10).join(bars)}
\addplot[only marks, mark=*, mark size=2.2pt, color=black!45]
  coordinates {{{" ".join(dead)}}};
\addlegendentry{{no human commit in 12 months}}
\addplot[only marks, mark=*, mark size=2.2pt, color=vislink]
  coordinates {{{" ".join(live)}}};
\addlegendentry{{still maintained}}
\draw[dashed, black!35] (axis cs:{snapshot:.2f},-0.8) --
                        (axis cs:{snapshot:.2f},{len(rows) - 0.4:.1f});
\end{{axis}}
\end{{tikzpicture}}
"""


# --------------------------------------------------------------------------
# Table 1 -- maintenance profile
# --------------------------------------------------------------------------
def table_maintenance(repos: dict) -> str:
    by_name = {r["name"]: r for r in repos["repositories"]}
    lines = []
    for name in TABLE_ROWS:
        r = by_name[name]
        lines.append(
            f"{r['slug'].split('/')[-1]} & "
            f"{tex_int(r['commits_human'])} & {tex_int(r['authors'])} & "
            f"{r['bus_factor_50']} & {100 * r['top_author_share']:.0f}\\% & "
            f"{tex_int(r['human_commits_12mo'])} & "
            f"{100 * r['bot_share_12mo']:.0f}\\% \\\\"
        )
    # \bottomrule must live inside this file: an \input whose last token is a
    # row terminator leaves TeX unable to see a following \noalign, so a
    # \bottomrule written in main.tex after the \input raises "Misplaced
    # \noalign". Closing the rule here keeps the call site a plain \input.
    return ("% Generated by scripts/make_figures.py -- do not edit.\n"
            + "\n".join(lines) + "\n\\bottomrule\n")


# --------------------------------------------------------------------------
# Macros
# --------------------------------------------------------------------------
def macros(repos: dict, eco: dict, schema: dict) -> str:
    by_name = {r["name"]: r for r in repos["repositories"]}
    vl = by_name["vega-lite"]
    vega_eco = next(e for e in eco["ecosystems"] if e["label"] == "Vega ecosystem")
    d3_fam = next(e for e in eco["ecosystems"] if e["label"] == "D3 family")

    rel = schema["releases"]
    first_rel, last_rel = rel[0], rel[-1]
    frozen = [r for r in rel if r["bytes"] == last_rel["bytes"]]
    peak_defs = max(r["definitions"] for r in rel)

    vl_peak_year, vl_peak = max(vl["per_year_human"].items(), key=lambda kv: kv[1])
    decline = 1 - vl["human_commits_12mo"] / int(vl_peak)

    # Dormancy is reported for exactly the systems drawn in the timeline
    # figure, so the count in the prose and the marks in the figure agree.
    timeline = [by_name[n] for n, _, _ in TIMELINE if n in by_name]
    dormant = [r for r in timeline if r["human_commits_12mo"] == 0]

    top3 = sum(a["share"] for a in vega_eco["top_authors"][:3])

    out = [
        "% Generated by scripts/make_figures.py -- do not edit.",
        rf"\newcommand{{\snapshot}}{{{date.fromisoformat(repos['snapshot']):%-d %B %Y}}}",
        # Vega-Lite
        rf"\newcommand{{\vlhuman}}{{{tex_int(vl['commits_human'])}}}",
        rf"\newcommand{{\vlauthors}}{{{tex_int(vl['authors'])}}}",
        rf"\newcommand{{\vlpeak}}{{{tex_int(int(vl_peak))}}}",
        rf"\newcommand{{\vlpeakyear}}{{{vl_peak_year}}}",
        rf"\newcommand{{\vlrecent}}{{{vl['human_commits_12mo']}}}",
        rf"\newcommand{{\vldecline}}{{{100 * decline:.0f}}}",
        rf"\newcommand{{\vlbotshare}}{{{100 * vl['bot_share_12mo']:.0f}}}",
        rf"\newcommand{{\vlbusfactor}}{{{vl['bus_factor_50']}}}",
        # ecosystem
        rf"\newcommand{{\ecorepos}}{{{len(vega_eco['repositories'])}}}",
        rf"\newcommand{{\ecocommits}}{{{tex_int(vega_eco['human_commits'])}}}",
        rf"\newcommand{{\ecohumans}}{{{tex_int(vega_eco['humans'])}}}",
        rf"\newcommand{{\ecobusfifty}}{{{vega_eco['bus_factor_50']}}}",
        rf"\newcommand{{\ecobuseighty}}{{{vega_eco['bus_factor_80']}}}",
        rf"\newcommand{{\ecotopthree}}{{{100 * top3:.0f}}}",
        rf"\newcommand{{\ecorecent}}{{{tex_int(vega_eco['human_commits_12mo'])}}}",
        rf"\newcommand{{\ecorecenthumans}}{{{vega_eco['humans_12mo']}}}",
        # D3
        rf"\newcommand{{\dthreecommits}}{{{tex_int(d3_fam['human_commits'])}}}",
        rf"\newcommand{{\dthreehumans}}{{{tex_int(d3_fam['humans'])}}}",
        rf"\newcommand{{\dthreetop}}{{{100 * d3_fam['top_authors'][0]['share']:.0f}}}",
        rf"\newcommand{{\dthreerecent}}{{{d3_fam['human_commits_12mo']}}}",
        # schema
        rf"\newcommand{{\schemareleases}}{{{len(rel)}}}",
        rf"\newcommand{{\schemafirstdefs}}{{{first_rel['definitions']}}}",
        rf"\newcommand{{\schemafirsttag}}{{{first_rel['tag']}}}",
        rf"\newcommand{{\schemafirstyear}}{{{first_rel['date'][:4]}}}",
        rf"\newcommand{{\schemapeakdefs}}{{{peak_defs}}}",
        rf"\newcommand{{\schemafirstkb}}{{{first_rel['bytes'] / 1024:.0f}}}",
        rf"\newcommand{{\schemalastmb}}{{{last_rel['bytes'] / 1048576:.2f}}}",
        rf"\newcommand{{\schemafrozen}}{{{len(frozen)}}}",
        rf"\newcommand{{\schemafrozenfrom}}{{{frozen[0]['tag']}}}",
        rf"\newcommand{{\schemafrozenfromdate}}{{{frozen[0]['date']}}}",
        rf"\newcommand{{\schemafrozento}}{{{frozen[-1]['tag']}}}",
        # dormancy
        rf"\newcommand{{\ntimeline}}{{{len(timeline)}}}",
        rf"\newcommand{{\ndormant}}{{{len(dormant)}}}",
        rf"\newcommand{{\falconlast}}{{{by_name['falcon']['last_human_commit']}}}",
        rf"\newcommand{{\voyagerlast}}{{{by_name['voyager']['last_human_commit']}}}",
        rf"\newcommand{{\dracolast}}{{{by_name['draco']['last_human_commit']}}}",
        rf"\newcommand{{\lyralast}}{{{by_name['lyra']['last_human_commit']}}}",
        rf"\newcommand{{\protovislast}}{{{by_name['protovis']['last_human_commit']}}}",
        rf"\newcommand{{\mosaicrecent}}{{{by_name['mosaic']['human_commits_12mo']}}}",
        rf"\newcommand{{\mplrecent}}{{{tex_int(by_name['matplotlib']['human_commits_12mo'])}}}",
        rf"\newcommand{{\mplbus}}{{{by_name['matplotlib']['bus_factor_50']}}}",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    repos = load("repos.json")
    eco = load("ecosystem.json")
    schema = load("schema.json")

    FIGDIR.mkdir(parents=True, exist_ok=True)
    outputs = {
        FIGDIR / "bots.tex": fig_bots(repos),
        FIGDIR / "timeline.tex": fig_timeline(repos),
        FIGDIR / "maintenance-table.tex": table_maintenance(repos),
        PAPER / "numbers.tex": macros(repos, eco, schema),
    }
    for path, body in outputs.items():
        path.write_text(body)
        print(f"wrote {path.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
